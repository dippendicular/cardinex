//go:build ignore

// gen_debias writes debias_table.go: the quantised-correlation curve g(r) for
// 2- and 4-bit codes, as constants. Run with `go generate ./quant`.
// Committing constants keeps Distance bit-identical on every platform, since
// math.Erfc and math.Exp are not guaranteed to round the same everywhere.
package main

import (
	"fmt"
	"math"
	"os"
	"strconv"
	"strings"
)

const tableSize = 400

// Uniform step in units of sigma: MSE-optimal for a Gaussian source.
var steps = map[uint8]float64{2: 0.996, 4: 0.335}

func stepSigma(b uint8) float64 { return steps[b] }

func main() {
	var out strings.Builder
	out.WriteString("// Code generated by gen_debias.go; DO NOT EDIT.\n\npackage quant\n\n")
	fmt.Fprintf(&out, "const tableSize = %d\n\n", tableSize)
	fmt.Fprintf(&out, "const (\n\tstep2 = %s\n\tstep4 = %s\n)\n\n",
		strconv.FormatFloat(steps[2], 'g', -1, 64), strconv.FormatFloat(steps[4], 'g', -1, 64))
	out.WriteString("// tables[b][k] = g(-1 + 2k/tableSize).\nvar tables = [5][]float64{\n")
	for _, b := range []uint8{2, 4} {
		fmt.Fprintf(&out, "\t%d: {", b)
		for k, v := range buildTable(b) {
			if k%4 == 0 {
				out.WriteString("\n\t\t")
			} else {
				out.WriteString(" ")
			}
			out.WriteString(strconv.FormatFloat(v, 'g', -1, 64) + ",")
		}
		out.WriteString("\n\t},\n")
	}
	out.WriteString("}\n")
	if err := os.WriteFile("debias_table.go", []byte(out.String()), 0o644); err != nil {
		panic(err)
	}
}

// buildTable computes g(r) = E[q(X)q(Y)] / E[q(X)^2] for standard normal X, Y
// with correlation r, where q maps to the odd-integer level of its bin.
func buildTable(b uint8) []float64 {
	levels := 1 << b
	step := stepSigma(b)
	edges := make([]float64, levels+1) // bin j is [edges[j], edges[j+1])
	edges[0], edges[levels] = math.Inf(-1), math.Inf(1)
	for j := 1; j < levels; j++ {
		edges[j] = (float64(j) - float64(levels)/2) * step
	}
	level := func(j int) float64 { return float64(2*j + 1 - levels) }
	phi := func(z float64) float64 { return 0.5 * math.Erfc(-z/math.Sqrt2) }

	var q2 float64
	for j := 0; j < levels; j++ {
		q2 += level(j) * level(j) * (phi(edges[j+1]) - phi(edges[j]))
	}

	const n = 1600 // Simpson panels over [-8, 8]
	h := 16.0 / n
	g := make([]float64, tableSize+1)
	g[0], g[tableSize] = -1, 1
	for k := 1; k < tableSize; k++ {
		r := -1 + 2*float64(k)/tableSize
		sd := math.Sqrt(1 - r*r)
		var acc float64
		for i := 0; i <= n; i++ {
			x := -8 + float64(i)*h
			w := 2.0
			if i == 0 || i == n {
				w = 1
			} else if i%2 == 1 {
				w = 4
			}
			jx := levels - 1
			for j := 0; j < levels-1; j++ {
				if x < edges[j+1] {
					jx = j
					break
				}
			}
			var m float64 // E[q(Y) | X = x]
			for j := 0; j < levels; j++ {
				m += level(j) * (phi((edges[j+1]-r*x)/sd) - phi((edges[j]-r*x)/sd))
			}
			acc += w * math.Exp(-x*x/2) * level(jx) * m
		}
		g[k] = acc * h / 3 / math.Sqrt(2*math.Pi) / q2
	}
	return g
}
